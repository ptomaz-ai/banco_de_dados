/*  VIEW:
-- VIEW SÃO PSEUDO-TABELA QUE GRAVAM SQL GRANDES PARA SEREM EXECUTADOS EM DIVERSAAS PARTES DO CODIGO, SEM RESCREER.
*/
-- CRIAR UMAVIEW PARA RETORNAR OS FUNCIONARIOS E SEUSSUPERMERCADOS

CREATE OR REPLACE VIEW VW_FUNSIONARIOS_SUPERMERCADOS AS 
SELECT	F.FUN_CPF AS "CPF",
		F.FUN_NOME AS "NOME",
		F.FUN_DATA_NASCIMENTO AS "DATA DE NACIENTO",
        F.FUN_TELEFONE AS "TELEFONE",
        F.FUN_EMAIL AS "EMAIL",
        F.FUN_CARTEIRA_TRABALHO AS "CARTEIRA DE TRABALHO",
        F.FUN_BANCO_AGENCIA AS "AGENCIA DO BANCO",
        F.FUN_BANCO_CONTA AS "CONTA DO BANCO",
        F.FUN_DATA_ADMISSAO AS "DATA DE ADIMISSÃO",
        F.FUN_JORNADA_TRABALHO AS "JORNADA DE TRABALHO"
FROM	FUNCIONARIO F
JOIN	SUPERMERCADO S ON (S.SUP_CNPJ = F.FK_SUP_CNPJ);

SELECT * FROM VW_FUNSIONARIOS_SUPERMERCADOS;

SELECT *
FROM VW_FUNSIONARIOS_SUPERMERCADOS
WHERE	UPPER(NOME) LIKE '%RAFAEL%';

