CREATE OR REPLACE VIEW VW_PRODUTO_VENCIMENTO AS
SELECT	PRO_NOME AS "NOME",
		PRO_PRECO AS "PRECO",
        PRO_QUANTIDADE AS "QUANTIDADE",
        PRO_DATA_VALIDADE AS "DATA DE VALIDADE",
        DATEDIFF(PRO_DATA_VALIDADE, CURDATE()) AS "DIAS DE VENCIMENTO"
FROM	PRODUTO
WHERE	DATEDIFF(PRO_DATA_VALIDADE, CURDATE()) <= 15;

SELECT * FROM VW_PRODUTO_VENCIMENTO;